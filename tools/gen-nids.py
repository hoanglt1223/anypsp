#!/usr/bin/env python3
"""Generate data/nids.toml: library, NID and function name for PSP system libraries.

Sources (both read from local checkouts, commits recorded in the output):
  - PPSSPP's HLE function tables (Core/HLE/*.cpp), GPL-2.0-or-later
  - PSPSDK's import stubs (src/**/*.S, IMPORT_FUNC lines), BSD

PPSSPP's name wins when both list a NID.

  python tools/gen-nids.py --ppsspp ../../refs/ppsspp --pspsdk ../../refs/pspsdk --out data/nids.toml
"""

import argparse
import hashlib
import pathlib
import re
import subprocess
import sys

TABLE = re.compile(r"(?:const\s+)?HLEFunction\s+(\w+)\s*\[\s*\]\s*=\s*\{(.*?)\n\};", re.S)
ENTRY = re.compile(r"\{\s*0[xX]([0-9A-Fa-f]{1,8})\s*,\s*[^,{}]+,\s*\"([^\"]*)\"")
REGISTER = re.compile(r"\"(\w+)\"\s*,\s*(?:ARRAY_SIZE|std::size)\((\w+)\)\s*,\s*(\w+)")
STUB = re.compile(r"^\s*IMPORT_FUNC(?:_WITH_ALIAS)?\s+\"(\w+)\"\s*,\s*0[xX]([0-9A-Fa-f]{8})\s*,\s*(\w+)", re.M)
NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def commit_of(path):
    try:
        return subprocess.run(["git", "-C", str(path), "rev-parse", "HEAD"], capture_output=True, text=True,
                              check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        sys.exit(f"{path} is not a git checkout; the source commit must be recorded")


def nid_of(name):
    return int.from_bytes(hashlib.sha1(name.encode()).digest()[:4], "little")


def ppsspp_entries(root):
    tables, registered = {}, []
    for source in sorted((root / "Core" / "HLE").glob("*.cpp")):
        text = source.read_text(encoding="utf-8", errors="replace")
        for ident, body in TABLE.findall(text):
            tables[ident] = [(int(nid, 16), name) for nid, name in ENTRY.findall(body)]
        registered += [(library, ident) for library, size_ident, ident in REGISTER.findall(text) if size_ident == ident]
    entries = []
    unmapped = set(tables)
    for library, ident in registered:
        if ident not in tables:
            continue
        unmapped.discard(ident)
        entries += [(library, nid, name) for nid, name in tables[ident]]
    return entries, sorted(unmapped)


def pspsdk_entries(root):
    entries = []
    for source in sorted(root.rglob("*.S")):
        text = source.read_text(encoding="utf-8", errors="replace")
        entries += [(library, int(nid, 16), name) for library, nid, name in STUB.findall(text)]
    return entries


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ppsspp", type=pathlib.Path, required=True)
    parser.add_argument("--pspsdk", type=pathlib.Path, required=True)
    parser.add_argument("--out", type=pathlib.Path, required=True)
    args = parser.parse_args()

    ppsspp, unmapped = ppsspp_entries(args.ppsspp)
    pspsdk = pspsdk_entries(args.pspsdk)
    if not ppsspp or not pspsdk:
        sys.exit("no entries found; check the --ppsspp and --pspsdk paths")

    libraries = {}
    conflicts = 0
    for library, nid, name in ppsspp + pspsdk:
        if not NAME.match(name):
            continue
        known = libraries.setdefault(library, {})
        if nid in known:
            conflicts += known[nid] != name
            continue
        known[nid] = name

    lines = [
        "# PSP system library NIDs and function names. Generated by tools/gen-nids.py; do not edit.",
        f"# PPSSPP {commit_of(args.ppsspp)} (Core/HLE function tables, GPL-2.0-or-later)",
        f"# PSPSDK {commit_of(args.pspsdk)} (import stubs, BSD)",
        "# A name whose SHA-1 does not give its NID comes from a firmware that randomised NIDs.",
        "",
    ]
    total = verified = 0
    for library in sorted(libraries):
        lines.append(f'["{library}"]')
        for nid in sorted(libraries[library]):
            name = libraries[library][nid]
            lines.append(f'0x{nid:08X} = "{name}"')
            total += 1
            verified += nid_of(name) == nid
        lines.append("")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{total} NIDs in {len(libraries)} libraries ({verified} match the SHA-1 of their name), "
          f"{conflicts} name conflicts kept as PPSSPP, unregistered PPSSPP tables: {', '.join(unmapped) or 'none'}")


if __name__ == "__main__":
    main()
